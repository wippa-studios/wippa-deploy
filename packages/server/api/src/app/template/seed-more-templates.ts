export async function seedMoreTemplates(log: FastifyBaseLogger): Promise<void> {
    const existing = await templateRepo().find({ where: { type: TemplateType.OFFICIAL } })
    const existingNames = new Set(existing.map(t => t.name))
    let addedCount = 0

    for (const tpl of MORE_TEMPLATES) {
        if (existingNames.has(tpl.name)) {
            continue
        }
        const prepared = await templateValidator.validateAndPrepare({
            flows: tpl.flows,
            platformId: undefined,
            log,
        })
        const template = {
            id: apId(),
            name: tpl.name,
            type: TemplateType.OFFICIAL,
            summary: tpl.summary,
            description: tpl.description,
            tags: tpl.tags,
            blogUrl: null,
            metadata: null,
            author: tpl.author,
            categories: tpl.categories,
            pieces: prepared.pieces,
            flows: prepared.flows,
            status: TemplateStatus.PUBLISHED,
            platformId: undefined,
            created: now(),
            updated: now(),
        }
        await templateRepo().save(template)
        addedCount++
    }

    if (addedCount > 0) {
        log.info(`Seeded ${addedCount} new templates`)
    }
}